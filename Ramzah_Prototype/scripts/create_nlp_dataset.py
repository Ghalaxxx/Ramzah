def targets(words):
    """Training-data helper; production inference never calls this."""
    wanted = frozenset(words)
    return next(
        phrases
        for concepts, phrases in EXAMPLES.items()
        if frozenset(concepts) == wanted
    )


def main():
    random.seed(42)
    out = Path("data/nlp")
    out.mkdir(parents=True, exist_ok=True)
    (out / "concepts.json").write_text(
        json.dumps(CONCEPTS, ensure_ascii=False, indent=2), encoding="utf8"
    )
    splits = {name: [] for name in ("train", "validation", "test")}
    groups = {name: set() for name in splits}
    for concepts, phrases in EXAMPLES.items():
        group_id = "|".join(sorted(concepts))
        orders = list(itertools.permutations(concepts))
        random.shuffle(orders)
        rows = []
        for order in orders[:6]:
            # Emphasize one unambiguous realization while retaining natural alternatives.
            for target in [phrases[0], phrases[0], phrases[0], *phrases[1:]]:
                rows.append(
                    {
                        "glosses": list(order),
                        "source": " ".join(order),
                        "target": target,
                        "references": phrases,
                        "concepts": sorted(concepts),
                        "group_id": group_id,
                        "provenance": "manually authored context-specific synthetic supervision; not patient data",
                    }
                )
        # Hold out exact rows. For multi-gloss groups the test source uses a word
        # order absent from training; for singletons its reference phrasing is absent.
        test_order = orders[-1]
        test_row = next(
            row
            for row in rows
            if tuple(row["glosses"]) == test_order and row["target"] == phrases[-1]
        )
        validation_target = phrases[-2] if len(phrases) > 2 else phrases[-1]
        validation_row = next(
            row
            for row in rows
            if row is not test_row and row["target"] == validation_target
        )
        splits["test"].append(test_row)
        splits["validation"].append(validation_row)
        groups["test"].add(group_id)
        groups["validation"].add(group_id)
        groups["train"].add(group_id)
        for row in rows:
            if row is not test_row and row is not validation_row:
                splits["train"].append(row)
    for split, rows in splits.items():
        random.shuffle(rows)
        (out / f"{split}.jsonl").write_text(
            "\n".join(json.dumps(row, ensure_ascii=False) for row in rows) + "\n",
            encoding="utf8",
        )
    card = {
        "counts": {name: len(rows) for name, rows in splits.items()},
        "groups": {name: len(value) for name, value in groups.items()},
        "seed": 42,
        "split_key": "exact (gloss order, target) pair; test uses held-out order for multi-gloss groups",
        "target_design": "context-specific manually authored Arabic with multiple natural realizations",
        "caveats": [
            "Synthetic examples",
            "No Deaf-user or clinician validation",
            "Gloss sequences may remain pragmatically ambiguous",
        ],
    }
    (out / "dataset_card.json").write_text(
        json.dumps(card, ensure_ascii=False, indent=2), encoding="utf8"
    )
    print(json.dumps(card, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
